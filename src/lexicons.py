def pos_tag(tokens):
    """Rule-based POS tagger: closed-class lexicon -> numeral rules -> open-class lexicons (exact then stem/lemma)
    -> contextual rules (demonstrative DET/PRON, 'کیا') -> morphological suffix rules -> UNK."""
    tags = []
    n = len(tokens)
    for i, t in enumerate(tokens):
        prv = tokens[i - 1] if i else ""
        nxt = tokens[i + 1] if i + 1 < n else ""
        tag = None
        if _PUNC_RE.match(t) and not _NUM_RE.match(t): tag = "PUNC"
        elif _NUM_RE.match(t): tag = "NUM"
        elif t == "کیا": tag = "PRON" if i == 0 or prv in ("اور", "تو", "لیکن", "مگر") else "VERB"
        elif t in ("ایک",) and (nxt in ("ہزار", "لاکھ", "کروڑ", "ارب", "سو", "سال", "بار", "ہی", "دن")): tag = "NUM"
        elif t in POST: tag = "POST"
        elif t in CONJ: tag = "CONJ"
        elif t in PART: tag = "PART"
        elif t in NUM_WORDS and t not in DET: tag = "NUM"
        elif t in AUX_FORMS: tag = "VERB"
        elif t in DEM_OR_PRON:
            nominal_next = (nxt and nxt not in POST and nxt not in CONJ and nxt not in PART and nxt not in AUX_FORMS
                            and nxt not in VERB_FORMS and nxt not in PRON)
            if t in ("یہ", "وہ", "اس", "ان", "اسی", "انہی", "جس", "جن", "کوئی", "کسی", "ہر", "تمام", "ایک", "دونوں", "سب", "کچھ"):
                tag = "DET" if nominal_next and t not in ("سب", "کچھ", "دونوں") else ("PRON" if t not in ("ہر", "ایک", "تمام") else "DET")
            else: tag = "PRON"
        elif t in PRON: tag = "PRON"
        elif t in DET: tag = "DET"
        if tag is None:
            if t in VERB_FORMS: tag = "VERB"
            elif t in ADV_FORMS: tag = "ADV"
            elif t in ADJ_FORMS and t not in NOUN_FORMS: tag = "ADJ"
            elif t in NOUN_FORMS: tag = "NOUN"
            elif t in ADJ_FORMS: tag = "ADJ"
        if tag is None:                                   # stem / lemma lookup
            for c in _cands(t):
                if c in VERB_FORMS and c != t and len(c) > 2: tag = "VERB"; break
                if c in NOUN_FORMS: tag = "NOUN"; break
                if c in ADJ_FORMS: tag = "ADJ"; break
                if c in ADV_FORMS: tag = "ADV"; break
        if tag is None:                                   # morphological rules
            if t in GAZ_WORDS: tag = "NOUN"
            elif re.search(r"(تا|تی|تے|تیں)$", t) and len(t) > 4 and re.sub(r"(تا|تی|تے|تیں)$", "", t) in VERB_ROOTS: tag = "VERB"
            elif re.search(r"(نے|نا)$", t) and len(t) > 4 and stem(t) in VERB_ROOTS: tag = "VERB"
            elif t.endswith(("ناک", "مند", "انہ", "یافتہ", "شدہ", "نما", "آمیز", "کن")) and len(t) > 4: tag = "ADJ"
            elif t.endswith("ی") and len(t) >= 5 and (t.endswith(("انی", "وی", "نوی", "ائی")) or t[:-1] in GAZ_WORDS): tag = "ADJ"
            elif t.endswith(("ا", "ی")) and len(t) >= 5 and t.endswith(("یا", "ایا", "ائی")) and stem(t) in VERB_ROOTS: tag = "VERB"
            elif t in _ABBR_LETTERS: tag = "NOUN"
            elif len(t) <= 2: tag = "UNK"
            else: tag = "NOUN"                            # open-class default: nominal
        tags.append(tag)
    return tags


