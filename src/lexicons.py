_MAP = {"ي": "ی", "ى": "ی", "ك": "ک"}


def norm(s):
    """Same normalisation that produced cleaned.txt (drop diacritics/ZWNJ, unify letter variants)."""
    s = unicodedata.normalize("NFC", s)
    out = []
    for ch in s:
        ch = _MAP.get(ch, ch); cat = unicodedata.category(ch)
        if ch.isspace(): out.append(" ")
        elif cat not in ("Mn", "Cf"): out.append(ch)
    return re.sub(r"\s+", " ", "".join(out)).strip()


def W(s):
    return [norm(w) for w in s.split()]


