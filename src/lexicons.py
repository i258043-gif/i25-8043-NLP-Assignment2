_SUFFIXES = sorted(["ئیں", "ایاں", "یوں", "وں", "یں", "یاں", "ات", "ئے", "ئی", "تے", "تی", "تا", "نے", "نا", "ے", "ی", "ا", "ں", "ہ"], key=len, reverse=True)


def stem(w):
    """Light suffix-stripping stemmer (plural/oblique/gender/verbal endings); min stem length 2."""
    for s in _SUFFIXES:
        if w.endswith(s) and len(w) - len(s) >= 2:
            return w[: -len(s)]
    return w


def lemma(w):
    """Lemmatizer: irregular verb forms map to their root through VERB_LEMMA, other tokens to the stem."""
    return VERB_LEMMA.get(w, stem(w))


def _cands(w):
    st = stem(w)
    return [w, st, st + "ا", st + "ہ", st + "ی"] if st != w else [w]


