GAZ = {"PER": PERSONS, "LOC": LOCATIONS, "ORG": ORGS, "MISC": MISC}
GAZ_WORDS = {w for g in GAZ.values() for e in g for w in e}
GAZ_COUNTS = {k: len(v) for k, v in GAZ.items()}
_PRIORITY = {"PER": 0, "ORG": 1, "LOC": 2, "MISC": 3}


def ner_tag(tokens):
    """Longest-match gazetteer BIO tagger (ties broken PER > ORG > LOC > MISC)."""
    idx = {}
    for typ, ents in GAZ.items():
        for e in ents: idx.setdefault(e, typ)
    maxlen = max(len(e) for e in idx)
    tags = ["O"] * len(tokens); i = 0
    while i < len(tokens):
        hit = None
        for L in range(min(maxlen, len(tokens) - i), 0, -1):
            e = tuple(tokens[i:i + L])
            if e in idx:
                # single-token matches that are also very common function/open words are skipped
                if L == 1 and e[0] in CLOSED_ALL: break
                hit = (L, idx[e]); break
        if hit:
            L, typ = hit
            tags[i] = "B-" + typ
            for j in range(1, L): tags[i + j] = "I-" + typ
            i += L
        else: i += 1
    return tags
