def _expand_open(base, kind):
    forms = set(base)
    for w in base:
        if kind == "NOUN":
            if w.endswith("ا"): forms |= {w[:-1] + "ے", w[:-1] + "وں"}
            elif w.endswith("ہ"): forms |= {w[:-1] + "ے", w[:-1] + "وں", w[:-1] + "ات"}
            elif w.endswith("ی"): forms |= {w + "اں", w[:-1] + "یاں", w[:-1] + "یوں"}
            else: forms |= {w + "وں", w + "یں", w + "ات"}
        elif kind == "ADJ":
            if w.endswith("ا"): forms |= {w[:-1] + "ی", w[:-1] + "ے", w[:-1] + "یں"}
    return {f for f in forms if " " not in f}


